const assert=require('node:assert/strict');

module.exports=async function verifySearchReview({send,evaluate,waitFor,screenshot}){
 const saved=await evaluate("localStorage.getItem('fe-kotoba-note-v1')");
 const input=async(id,value)=>evaluate(`(()=>{const field=document.getElementById(${JSON.stringify(id)});field.focus();field.value=${JSON.stringify(value)};field.dispatchEvent(new Event('input',{bubbles:true}))})()`);
 const select=async(id,value)=>evaluate(`document.getElementById(${JSON.stringify(id)}).value=${JSON.stringify(value)};document.getElementById(${JSON.stringify(id)}).dispatchEvent(new Event('change',{bubbles:true}))`);
 const names=async()=>evaluate("[...document.querySelectorAll('.word-name')].map(node=>node.textContent)");
 try{
  await evaluate("localStorage.setItem('fe-kotoba-note-v1',JSON.stringify({version:1,activeProfileId:'ui-review',profiles:[{id:'ui-review',name:'UI確認',flags:{},notes:{},history:[],customTerms:[]}]}))");
  await send('Page.reload');
  await waitFor("document.querySelector('#home-search')");
  await send('Emulation.setDeviceMetricsOverride',{width:320,height:700,deviceScaleFactor:1,mobile:true});
  assert.equal(await evaluate("document.querySelectorAll('#bottom-nav button').length"),4);
  await evaluate("document.querySelector('#home-search').value='ＲＦＩＤ';document.querySelector('#home-search-form').requestSubmit()");
  assert.equal((await names())[0],'RFID','Home search must work without selecting a genre');
  await evaluate("document.querySelector('.check-button').click()");
  assert.equal(await evaluate("document.querySelector('.nav-count').textContent"),'1');
  await input('global-search','ディーラム');
  assert.equal((await names())[0],'DRAM','Katakana queries must match hiragana readings');
  assert.equal(await evaluate("document.activeElement.id"),'global-search','Typing must retain focus');
  await evaluate("document.querySelector('.check-button').click()");
  await input('global-search','ICカード');
  assert.equal((await names())[0],'ICカード','Exact term matches must rank first');
  await evaluate("document.querySelector('.check-button').click()");
  await input('global-search','ICカード RFID');
  assert.ok((await names()).includes('ICカード'),'AND search must include explanations');
  assert.ok((await names()).includes('RFID'));
  await screenshot('mobile-ui-search-test.png');
  assert.equal(await evaluate('document.documentElement.scrollWidth>innerWidth'),false);
  await input('global-search','見つからない用語xyz');
  assert.equal((await names()).length,0);
  assert.equal(await evaluate("document.querySelector('[data-action=study-search]').disabled"),true);
  await evaluate("document.querySelector('[data-action=clear-search]').click()");
  assert.equal(await evaluate("document.querySelector('#global-search').value"),'');
  assert.equal((await names()).length,60);
  await evaluate("document.querySelector('[data-action=more-search]').click()");
  assert.equal((await names()).length,120);
  await evaluate("document.querySelector('[data-action=search-new-only]').click()");
  await select('search-scope','11');
  const securityCount=await evaluate("[...document.querySelectorAll('.word-item')].length");
  assert.equal(securityCount,51);
  assert.equal(await evaluate("document.querySelectorAll('.word-item .added-tag').length"),51);
  await evaluate("document.querySelector('[data-action=search-checked-only]').click()");
  assert.equal((await names()).length,0,'Unmarked checked words must not enter new-syllabus-only results');
  await evaluate("document.querySelector('[data-action=reset-search]').click()");
  await input('global-search','DRAM');
  await evaluate("document.querySelector('[data-action=study-search]').click()");
  assert.equal(await evaluate("document.querySelector('.card-term').textContent"),'DRAM');
  assert.ok((await evaluate("document.querySelector('[data-action=back-study]').textContent")).includes('検索結果'));
  assert.equal(await evaluate("document.querySelector('[data-action=start-list]')===null"),true);
  await evaluate("document.querySelector('[data-action=back-study]').click()");
  assert.equal(await evaluate("document.querySelector('#global-search').value"),'DRAM');
  await evaluate("document.querySelector('[data-action=nav][data-screen=checked]').click()");
  assert.equal((await names()).length,3);
  await select('checked-scope','11');
  assert.deepEqual(await names(),['ICカード']);
  await input('checked-search','DRAM');
  assert.equal((await names()).length,0);
  assert.equal(await evaluate("document.querySelector('[data-action=study-checked]').disabled"),true);
  await evaluate("document.querySelector('[data-action=reset-checked-filter]').click()");
  assert.equal((await names()).length,3);
  await screenshot('mobile-ui-checked-test.png');
  await evaluate("window.scrollTo(0,document.body.scrollHeight)");
  assert.equal(await evaluate("(()=>{const rows=document.querySelectorAll('.word-item');return rows[rows.length-1].getBoundingClientRect().bottom<=document.querySelector('.selection-bar').getBoundingClientRect().top})()"),true,'Footer must not obscure the final checked word');
  assert.equal(await evaluate('document.documentElement.scrollWidth>innerWidth'),false);
  await input('checked-search','でぃーらむ');
  await evaluate("document.querySelector('[data-action=shuffle-study]').click();document.querySelector('[data-action=study-checked]').click()");
  assert.equal(await evaluate("document.querySelector('.card-term').textContent"),'DRAM');
  assert.ok((await evaluate("document.querySelector('.study-progress span').textContent")).includes('1 / 1'));
  await evaluate("document.querySelector('.study-check').click();document.querySelector('[data-action=back-study]').click()");
  assert.equal((await names()).length,0,'Unchecking a word must update the filtered review deck');
  assert.equal(await evaluate("document.querySelector('#checked-total-count').textContent"),'2');
  await evaluate("document.querySelector('[data-action=clear-checked-search]').click()");
  await select('checked-scope','3');
  assert.deepEqual(await names(),['RFID']);
  await evaluate("document.querySelector('[data-action=study-checked]').click()");
  assert.equal(await evaluate("document.querySelector('.card-term').textContent"),'RFID');
  await evaluate("document.querySelector('[data-action=back-study]').click();document.querySelector('.check-button').click()");
  assert.equal((await names()).length,0);
  const persisted=await evaluate("(()=>{const s=JSON.parse(localStorage.getItem('fe-kotoba-note-v1'));return Object.keys(s.profiles[0].flags).length})()");
  assert.equal(persisted,1,'Only the IC card check must remain');
  console.log('Search/review UI: global search, kana/width normalization, explanation AND search, exact-match ranking, pagination, 448-word filter scope, keyword/genre review, shuffle, empty states and 320px footer layout passed.');
 }finally{
  await evaluate(`localStorage.setItem('fe-kotoba-note-v1',${JSON.stringify(saved)})`);
  await send('Page.reload');
  await waitFor("document.querySelector('#home-search')");
 }
};
